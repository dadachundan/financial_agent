def _zhfont(run):
    rPr2 = run.element.get_or_add_rPr()
    rFonts2 = OxmlElement("w:rFonts"); rFonts2.set(qn("w:eastAsia"), ZH_FONT); rPr2.append(rFonts2)

def add_para(text, bold=False, italic=False, color=None, size=11, align=None):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.name = "Times New Roman"; r.font.size = Pt(size)
    r.font.bold = bold; r.font.italic = italic
    if color: r.font.color.rgb = color
    if align: p.alignment = align
    _zhfont(r)

def add_image(path, width_inches=6.5, caption=None):
    if not os.path.exists(path):
        add_para(f"[图表未找到: {path}]", italic=True, color=GREY); return
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(); r.add_picture(path, width=Inches(width_inches))
    if caption:
        cap = doc.add_paragraph(); cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
        cr = cap.add_run(caption); cr.font.size = Pt(9); cr.font.italic = True; cr.font.color.rgb = GREY
        _zhfont(cr)

def add_chart(num, desc, width=6.5):
    files = [f for f in os.listdir(CHARTS_DIR) if f.startswith(f"chart_{num:02d}_") and f.endswith(".png")]
    if files:
        add_image(os.path.join(CHARTS_DIR, files[0]), width_inches=width, caption=f"图表 {num}: {desc}")

def add_table_styled(headers, rows, col_widths=None, header_color="1F4E79"):
    t = doc.add_table(rows=len(rows)+1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER; t.style = "Light Grid Accent 1"
    for i, h in enumerate(headers):
        cell = t.rows[0].cells[i]; cell.text = ""
        p = cell.paragraphs[0]
        r = p.add_run(h); r.font.bold = True; r.font.color.rgb = RGBColor(255,255,255)
        r.font.name = "Times New Roman"; r.font.size = Pt(10); _zhfont(r)
        tcPr = cell._tc.get_or_add_tcPr()
        shd = OxmlElement("w:shd"); shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto")
        shd.set(qn("w:fill"), header_color); tcPr.append(shd)
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for ri, row in enumerate(rows, start=1):
        for ci, val in enumerate(row):
            cell = t.rows[ri].cells[ci]; cell.text = ""
            p = cell.paragraphs[0]
            r = p.add_run(str(val)); r.font.name = "Times New Roman"; r.font.size = Pt(10); _zhfont(r)
            if ci == 0: r.font.bold = True
            else: p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    if col_widths:
        for i, w in enumerate(col_widths):
            for row in t.rows: row.cells[i].width = Inches(w)
    return t

